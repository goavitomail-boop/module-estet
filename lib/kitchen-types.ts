/**
 * Страницы /kuhni/<тип>: угловые, без ручек, классические, современные.
 *
 * Это коммерческие запросы («угловые кухни на заказ»), по которым у
 * небольшой компании больше шансов, чем по «кухни на заказ». Каждая страница
 * — свой текст и наши проекты этого типа. Проекты подбираются по словам в их
 * описании из панели «Портфолио»: новая угловая кухня со словом «угловая» в
 * описании встанет на страницу сама.
 *
 * Страница показывается, только если проектов не меньше MIN_PROJECTS:
 * Яндекс считает малоинформативными страницы-подборки с одной-двумя
 * позициями. Поэтому «Прямых кухонь» пока нет — их в портфолио две.
 */
export const MIN_PROJECTS = 3

export type KitchenType = {
  slug: string
  /** H1 и название в списках */
  title: string
  /** Короткое название для ссылок: «Угловые» */
  short: string
  metaTitle: string
  description: string
  /** Абзацы над подборкой; ссылки — [текст](/адрес) */
  intro: string[]
  matches: (project: PortfolioProject) => boolean
}

const text = (project: PortfolioProject) =>
  [project.title, project.tag, project.alt, project.style, project.description, ...project.features, ...project.materials].join(' ')

const isClassic = (project: PortfolioProject) => /классик|прованс/i.test(project.style)

