export function getKitchenType(slug: string): KitchenType | undefined {
  return kitchenTypes.find((type) => type.slug === slug)
}

/** Типы, на которые набралось достаточно проектов, — с самими проектами */
export function kitchenTypesWithProjects(projects: PortfolioProject[]) {
  return kitchenTypes
    .map((type) => ({ type, projects: projects.filter(type.matches) }))
    .filter((entry) => entry.projects.length >= MIN_PROJECTS)
}
